import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {parseLessonMetadata,inspectGoalContract} from '../scripts/lesson-quality.mjs';
const dir=new URL('../classes/4/03-mala-ojczyzna-lobzow/',import.meta.url);
const read=name=>readFile(new URL(name,dir),'utf8');
test('Two separated local-history sessions have complete lean print inventory',async()=>{
 const m=parseLessonMetadata(await read('metadata.json'));
 assert.equal(m.presentation_mode,'none');assert.equal(m.curriculum_version,'nowa-2026');
 assert.deepEqual(m.sessions.map(s=>s.duration_minutes),[45,45]);
 assert.equal([5,5,25,7,3].reduce((a,b)=>a+b),45);
 assert.equal([4,5,18,12,6].reduce((a,b)=>a+b),45);
 assert.equal([4,4,4,3,3].reduce((a,b)=>a+b),18);
 assert.equal(m.print_plan.student_sheets,5+18+5);
 assert.equal(m.print_plan.total_sheets,28+5+2);
 const lesson=await read('lesson.md'),assessment=await read('assessment.md');
 const goal=inspectGoalContract({metadata:m,lessonMarkdown:lesson,assessmentMarkdown:assessment,slides:[]});
 assert.deepEqual(goal.errors,[]);assert.deepEqual(goal.warnings,[]);
 const stations=await read('stations.md');assert.equal(stations.split('<!-- page -->').length,5);
 assert.equal((await read('projects.md')).split('<!-- page -->').length,5);
 assert.equal((await read('teacher-guide.md')).split('<!-- page -->').length,5);
 assert.equal(assessment.split('<!-- page -->').length,2);
 assert.match(assessment,/3, 2, 4, 1/);assert.match(assessment,/Brak jawnie fantastycznego/);
 const legend=stations.split('# 4.')[1].split('<!-- page -->')[0];
 for(const text of ['Pewnego dnia książę litewski Giedymin','za [...] jeleniem','[Po polowaniu]','[szybki]','[dawniej: potok lub strumień]','wybudowano dwór, potem i wieś o nazwie Biały Stok.'])assert.ok(legend.includes(text),text);
 assert.ok(lesson.includes('nie zaliczamy lokalnej części 2.5'));
 const packet=await read('packet.html');assert.equal((packet.match(/data-page="/g)||[]).length,11);
 assert.equal((packet.match(/class="workspace"/g)||[]).length,5);
 assert.equal((packet.match(/<img /g)||[]).length,3);
 assert.equal((packet.match(/<img src="data:image\/png;base64,/g)||[]).length,3);
 assert.doesNotMatch(packet,/<script|<link|<iframe|<img src="https?:|Klucz • lekcja|Kolejność numerów/);
 assert.equal((await read('worksheet.html')).match(/data-page="/g).length,1);
 const provenance=JSON.parse(await read('assets/provenance.json'));
 assert.equal(provenance.osm.tiles.length,15);
 for(const [file,v] of Object.entries(provenance.files))assert.equal(createHash('sha256').update(await readFile(new URL('assets/'+file,dir))).digest('hex'),v.sha256);
});
