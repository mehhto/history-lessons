import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile,readdir} from 'node:fs/promises';
const dir=new URL('../classes/7/10-powtorka-ziemie-polskie-1815-1848/',import.meta.url);
test('Powtórka VII: pięć tematów, pełny klucz, bez prezentacji i odpowiedzi na karcie ucznia',async()=>{
  const read=name=>readFile(new URL(name,dir),'utf8');
  const [guide,taboo,key,worksheet,html,meta]=await Promise.all(['teacher-guide.md','taboo.md','assessment.md','worksheet.md','worksheet.html','metadata.json'].map(read));
  const m=JSON.parse(meta);
  assert.equal(m.grade,7); assert.equal(m.lesson_type,'practice'); assert.equal(m.presentation_mode,'none');
  assert.equal(m.teacher_reviewed,false); assert.equal(m.pdf_exported,false);
  const expected=['Królestwo Polskie','Powstanie listopadowe','Konstytucja','Cenzura','Wielka Emigracja','Rabacja galicyjska','Romantyzm','Adam Mickiewicz','Fryderyk Chopin','Paryż'];
  assert.deepEqual([...taboo.matchAll(/^## \d+\. (.+)$/gm)].map(x=>x[1]),expected);
  const cards=await read('taboo-do-wyciecia.html');
  assert.equal((cards.match(/class="card"/g)||[]).length,10);
  assert.ok(!cards.includes('Dopowiedzenie nauczyciela'));
  const qa=await read('pytania-i-odpowiedzi.html');
  assert.equal((qa.match(/class="qa-row"/g)||[]).length,25);
  const questionBlock=guide.split('## Bank 25 pytań')[1].split('## Popraw błędy')[0];
  assert.deepEqual([...questionBlock.matchAll(/^(\d+)\./gm)].map(x=>Number(x[1])),Array.from({length:25},(_,i)=>i+1));
  const answerBlock=key.split('## Bank pytań')[1].split('## Popraw błędy')[0];
  assert.deepEqual([...answerBlock.matchAll(/^(\d+)\./gm)].map(x=>Number(x[1])),Array.from({length:25},(_,i)=>i+1));
  for(const name of ['Po upadku','Powstanie listopadowe','Wielka Emigracja','Wiosna Ludów','Kultura polska'])assert.ok(guide.includes(name),name);
  assert.ok(key.includes('29/30 XI 1830')); assert.ok(key.includes('1846')); assert.ok(key.includes('Galicji w 1848'));
  assert.ok(!worksheet.includes('model odpowiedzi')); assert.ok(!html.includes('Dopowiedzenie nauczyciela'));
  assert.ok(!html.includes('assessment.md')); assert.ok(!html.includes('<script'));
  for(const filename of ['worksheet.html','teacher-guide.html'])assert.ok(!/<(?:script|link|img)[^>]*(?:src|href)=["']https?:/i.test(await read(filename)));
  const entries=await readdir(dir); for(const name of ['slides.md','index.html','presentation-backup.pdf'])assert.ok(!entries.includes(name),name);
  assert.equal([3,5,8,12,10,4,3].reduce((a,b)=>a+b),45);
  assert.equal([2,4,5,8,6,3,2].reduce((a,b)=>a+b),30);
});
