import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, access } from 'node:fs/promises';
import { parseSlideDirectives, auditSlideContract } from '../scripts/slide-contract.mjs';
const dir = new URL('../classes/7/09-kultura-polska-pod-zaborami/', import.meta.url);
test('Kultura pod zaborami: kompletny pakiet, widoczny zakres i uczciwe rozróżnienia', async () => {
  for (const name of ['lesson.md','teacher-guide.md','student-summary.md','worksheet.md','assessment.md','sources.md','reflection.md','lesson.css','index.html','metadata.json']) await access(new URL(name,dir));
  const md=await readFile(new URL('slides.md',dir),'utf8');
  const blocks=md.split(/\r?\n---\r?\n/);
  assert.equal(blocks.length,26);
  assert.equal(blocks.filter(b=>/^notes:/m.test(b)).length,26);
  assert.deepEqual(auditSlideContract(parseSlideDirectives(md),{lessonType:'new-knowledge'}).errors,[]);
  const visible=blocks.map(b=>b.split(/^notes:/m)[0]).join('\n');
  for(const term of ['elementarne','zawodowe','1816','1818','Przyjaciół Nauk','Adam Jerzy Czartoryski','Zakład Narodowy im. Ossolińskich','1822','1864','Kórnik','Łańcut','1825','Lilla Weneda','Czucie i wiara','Słowacki','Grottger','Mickiewicz','Chopin','Paryż','mesjanizm','Andrzej Towiański','Towianizm','Joachim Lelewel','Moniuszko','Piotr Michałowski']) assert.ok(visible.toLocaleLowerCase('pl').includes(term.toLocaleLowerCase('pl')),term);
  assert.match(visible,/Słuchaj dzieweczko!/);
  assert.match(visible,/gawiedzi \[gapiów\]/);
  assert.match(visible,/A gmin \[lud\] rozumowi bluźni/);
  assert.match(visible,/Miej serce i patrzaj w serce/);
  assert.match(visible,/nie obiektywny los Polski/);
  assert.match(visible,/nie synonim całego romantyzmu/);
  assert.match(visible,/Nie oznaczało to wszędzie równego dostępu/);
  assert.ok(md.indexOf('id="bilet"')<md.indexOf('id="notatka-instytucje"'));
  assert.match(blocks.at(-1),/id="notatka-tworcy"/);
  assert.doesNotMatch(visible,/<section\b|https?:\/\/[^\s]+\.(jpg|png)/);
  for(const [,asset] of md.matchAll(/<img[^>]+src="([^"]+)"/g)) await access(new URL(asset,dir));
  const meta=JSON.parse(await readFile(new URL('metadata.json',dir),'utf8'));
  assert.equal(meta.id,'09-kultura-polska-pod-zaborami');
  assert.equal(meta.curriculum_version,'stara-przejsciowa');
  for(const flag of ['source_reviewed','teacher_reviewed','pdf_exported']) assert.equal(meta[flag],false);
});
